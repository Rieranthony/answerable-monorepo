import { fileURLToPath } from "node:url"
import { Client, Pool } from "pg"
import { roleLock } from "../names"
import type { McpLogins, Sql } from "../provision"
import { mcpPostgresTestConfig } from "../testing"

/** The shared MCP test database, `answerable_mcps_test`, as the development superuser (`MCPS_TEST_DATABASE_URL`). */
export const mcpsUrl = mcpPostgresTestConfig.read(process.env).MCPS_TEST_DATABASE_URL

/** A superuser URL to the development cluster's `postgres` database, which `ensureLocalMcpDatabases` takes. */
export const clusterUrl = Object.assign(new URL(mcpsUrl), { pathname: "/postgres" }).href

/** The local logins `ensureLocalMcpDatabases` makes, whose password is `answerable`. */
export const localLogins: McpLogins = { migrator: "answerable_mcps_migrator", toolbox: "answerable_mcps_toolbox", standalone: "answerable_mcps_standalone" }

/** `url` with `login` and its password in place of the superuser's. */
export function as(login: string, password = "answerable", url = mcpsUrl) {
  const location = new URL(url)
  location.username = login
  location.password = password
  return location.href
}

/** A fixture MCP's drizzle folder, generated by drizzle-kit from `fixtures/<name>.ts` without its schema line. */
export const fixtureFolder = (name: "mpgfixa" | "mpgfixb") => fileURLToPath(new URL(`fixtures/${name}`, import.meta.url))

/** The `Sql` provisioning takes, on one client or a pool of one. */
export const sqlOf = (client: Client | Pool): Sql => async (text, params) => (await client.query(text, params)).rows

/** `statements` in one transaction under the lock every role statement takes, so that suites running beside each other never race on roles. */
const underRoleLock = (admin: Pool, statements: string) => admin.query(`begin; select pg_advisory_xact_lock(${roleLock}); ${statements}; commit`)

/** Drop what the tests made for each MCP of `names` in the shared test database: its schema and its two `mcp_test` roles. */
export async function forget(admin: Pool, ...names: string[]) {
  for (const name of names) await underRoleLock(admin, `drop schema if exists ${name} cascade; drop role if exists mcp_test_${name}_owner; drop role if exists mcp_test_${name}`)
}

/** A login with a generated name and password, made by the superuser at `url` with `attributes`; `drop()` removes it and what it was granted there. */
export async function testLogin(admin: Pool, attributes = "noinherit", url = mcpsUrl) {
  const name = `mcp_test_login_${crypto.randomUUID().replaceAll("-", "")}`
  const password = crypto.randomUUID().replaceAll("-", "")
  await admin.query(`create role ${name} login password '${password}' ${attributes}`)
  return { name, url: as(name, password, url), drop: () => underRoleLock(admin, `drop owned by ${name}; drop role ${name}`) }
}

/** A connected client as `url`, closed by the caller. */
export async function clientOf(url: string) {
  const client = new Client({ connectionString: url })
  await client.connect()
  return client
}
